import puppeteer from 'puppeteer-core';
import path from 'node:path';
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
const src=path.resolve('tmp-e2e/pages-m3.pdf');
const dest=path.resolve('tmp-e2e/pages-extracted.pdf');
try{fs.rmSync(dest,{force:true})}catch{}
const fill=(title,p)=>{console.log(execFileSync('pwsh',['-NoProfile','-File','scripts/fill-file-dialog.ps1','-Title',title,'-Path',p],{encoding:'utf8'}));};
const b=await puppeteer.connect({browserURL:'http://127.0.0.1:9333',defaultViewport:null});
const p=(await b.pages()).find(x=>x.url().includes('1420')||x.url().includes('tauri'));
await p.evaluate((pdfPath)=>{localStorage.setItem('voluma.recents.v1',JSON.stringify([{path:pdfPath,name:'pages-m3',size:4684,pages:5,lastPage:1,zoom:100,updatedAt:Date.now()}]))},src);
await p.reload({waitUntil:'networkidle2'}); await sleep(1200);
await p.waitForSelector('.recent-row',{timeout:10000}); await p.click('.recent-row');
await p.waitForFunction(()=>document.querySelectorAll('.page-wrap canvas').length>0,{timeout:20000});
await p.waitForFunction(()=>document.querySelector('.save-chip')?.textContent==='已保存',{timeout:10000});
await p.click('button[aria-label="页面管理"]'); await p.waitForSelector('.pm',{timeout:10000}); await sleep(500);
await p.evaluate(()=>{const b=[...document.querySelectorAll('.pm-tools button')].find(x=>x.textContent.includes('提取'));b.click();});
await sleep(500);
fill('提取选中页',dest);
for(let i=0;i<20&&!fs.existsSync(dest);i++) await sleep(300);
console.log('exists',fs.existsSync(dest),fs.existsSync(dest)?fs.statSync(dest).size:0);
await sleep(700);
const res=await p.evaluate(async(d)=>({pages:await window.__TAURI_INTERNALS__.invoke('document_page_count',{path:d}),toast:document.querySelector('.toast')?.textContent,sub:document.querySelector('.pm-sub')?.textContent}),dest);
console.log('extract',res);
await p.screenshot({path:'review-m2/49-extract-selected.png'});
await b.disconnect();
