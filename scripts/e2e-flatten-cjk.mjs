import puppeteer from 'puppeteer-core';
import path from 'node:path';
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
const src=path.resolve('tmp-e2e/forms-m3-cjk.pdf');
fs.copyFileSync(path.resolve('assets/M3-表单样本.pdf'),src);
const dest=path.resolve('tmp-e2e/forms-flat-cjk.pdf');
try{fs.rmSync(dest,{force:true})}catch{}
const fill=(title,p)=>{console.log(execFileSync('pwsh',['-NoProfile','-File','scripts/fill-file-dialog.ps1','-Title',title,'-Path',p],{encoding:'utf8'}));};
const b=await puppeteer.connect({browserURL:'http://127.0.0.1:9333',defaultViewport:null});
const p=(await b.pages()).find(x=>x.url().includes('1420')||x.url().includes('tauri'));
p.on('dialog',async d=>{console.log('dialog',d.message());await d.accept();});
await p.evaluate((pdfPath)=>{localStorage.setItem('voluma.recents.v1',JSON.stringify([{path:pdfPath,name:'forms-m3-cjk',size:8173,pages:1,lastPage:1,zoom:100,updatedAt:Date.now()}]))},src);
await p.reload({waitUntil:'networkidle2'}); await sleep(1200);
await p.waitForSelector('.recent-row',{timeout:10000}); await p.click('.recent-row');
await p.waitForFunction(()=>document.querySelectorAll('.widgetLayer input').length>0,{timeout:20000});
await sleep(700);
const typeIn=async(el,text)=>{await el.click();await p.keyboard.down('Control');await p.keyboard.press('A');await p.keyboard.up('Control');await p.keyboard.type(text);};
const texts=await p.$$('.widgetLayer input[type="text"]');
await typeIn(texts[0],'方小明');
await typeIn(texts[1],'小方工作室');
const ta=await p.$('.widgetLayer textarea'); await typeIn(ta,'第一行备注\n第二行备注');
await p.select('.widgetLayer select','Shenzhen');
await p.click('.widgetLayer input[type="checkbox"]');
const radios=await p.$$('.widgetLayer input[type="radio"]'); await radios[1].click();
await sleep(1800);
console.log('chip',await p.evaluate(()=>document.querySelector('.save-chip')?.textContent));
await p.click('button[aria-label="表单"]'); await p.waitForSelector('.form-panel',{timeout:5000});
await p.evaluate(()=>{const b=[...document.querySelectorAll('.form-panel button')].find(x=>x.textContent.includes('导出展平'));if(!b)throw new Error('no flatten btn');b.click();});
await sleep(500);
fill('导出展平 PDF',dest);
for(let i=0;i<24&&!fs.existsSync(dest);i++) await sleep(250);
await sleep(1000);
console.log('toast',await p.evaluate(()=>document.querySelector('.toast')?.textContent));
console.log('exists',fs.existsSync(dest),fs.existsSync(dest)?fs.statSync(dest).size:0);
await p.screenshot({path:'review-m2/57-flatten-cjk-done.png'});
await b.disconnect();
