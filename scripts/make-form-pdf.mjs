import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import fs from 'node:fs';
const doc=await PDFDocument.create();
const page=doc.addPage([595.28,841.89]);
const font=await doc.embedFont(StandardFonts.Helvetica);
const bold=await doc.embedFont(StandardFonts.HelveticaBold);
page.drawText('Voluma Form Sample',{x:54,y:780,size:24,font:bold,color:rgb(0.69,0.16,0.22)});
page.drawText('Fill the fields below, then save or flatten.',{x:54,y:748,size:11,font,color:rgb(0.2,0.2,0.2)});
const label=(t,y)=>page.drawText(t,{x:54,y,size:11,font,bold});
label('Name',700); label('Company',660); label('Agree to terms',620); label('Plan',580); label('City',540); label('Notes',460);
const form=doc.getForm();
const name=form.createTextField('name'); name.addToPage(page,{x:120,y:690,width:300,height:24});
const company=form.createTextField('company'); company.addToPage(page,{x:120,y:650,width:300,height:24});
const agree=form.createCheckBox('agree'); agree.addToPage(page,{x:120,y:612,width:16,height:16});
const plan=form.createRadioGroup('plan'); plan.addOptionToPage('Basic',page,{x:120,y:570,width:16,height:16}); plan.addOptionToPage('Pro',page,{x:220,y:570,width:16,height:16});
const city=form.createDropdown('city'); city.addOptions(['Beijing','Shanghai','Shenzhen']); city.addToPage(page,{x:120,y:530,width:200,height:26});
const notes=form.createTextField('notes'); notes.enableMultiline(); notes.addToPage(page,{x:54,y:320,width:480,height:120});
for (const f of [name, company, city, notes]) f.setFontSize(12);
form.updateFieldAppearances(font);
const bytes=await doc.save();
fs.writeFileSync('assets/M3-表单样本.pdf',bytes);
console.log(bytes.length);
