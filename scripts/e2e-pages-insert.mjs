import puppeteer from 'puppeteer-core';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
const pdf=path.resolve('assets/M0-阅读样本.pdf');
const img=path.resolve('review-m2/40-page-manager.png');
const fill=(title,p)=>{console.log(execFileSync('pwsh',['-NoProfile','-File','scripts/fill-file-dialog.ps1','-Title',title,'-Path',p],{encoding:'utf8'}));};
const b=await puppeteer.connect({browserURL:'http://127.0.0.1:9333',defaultViewport:null});
const p=(await b.pages()).find(x=>x.url().includes('1420')||x.url().includes('tauri'));
p.on('dialog',async d=>{ console.log('dialog',d.message()); await d.accept(); });
await p.evaluate((pdfPath)=>{localStorage.setItem('voluma.recents.v1',JSON.stringify([{path:pdfPath,name:'pages-insert',size:4684,pages:5,lastPage:1,zoom:100,updatedAt:Date.now()}]))},path.resolve('tmp-e2e/pages-insert.pdf'));
await p.reload({waitUntil:'networkidle2'}); await sleep(1200);
await p.waitForSelector('.recent-row',{timeout:10000}); await p.click('.recent-row');
await p.waitForFunction(()=>document.querySelectorAll('.page-wrap canvas').length>0,{timeout:20000});
await p.waitForFunction(()=>document.querySelector('.save-chip')?.textContent==='已保存',{timeout:10000});
await p.click('button[aria-label="页面管理"]'); await p.waitForSelector('.pm',{timeout:10000}); await sleep(500);
const btn=async(txt)=>{ await p.evaluate((t)=>{const b=[...document.querySelectorAll('.pm-tools button')].find(x=>x.textContent.includes(t)); if(!b) throw new Error('no button '+t); b.click();},txt); await sleep(500); };
await btn('插入 PDF');
fill('选择要插入的 PDF',pdf);
await p.waitForFunction(()=>document.querySelectorAll('.pm-insert').length===1,{timeout:20000});
await sleep(400);
await p.screenshot({path:'review-m2/45-insert-pdf-staged.png'});
console.log('after pdf',await p.evaluate(()=>({cards:document.querySelectorAll('.pm-card').length,inserts:document.querySelectorAll('.pm-insert').length,sub:document.querySelector('.pm-sub')?.textContent})));
await p.click('.pm-card[data-page="5"]'); await sleep(150);
await btn('插入图片');
fill('选择要插入的图片',img);
await p.waitForFunction(()=>document.querySelectorAll('.pm-insert').length===2,{timeout:20000});
await sleep(400);
await p.screenshot({path:'review-m2/46-insert-image-staged.png'});
console.log('after image',await p.evaluate(()=>({cards:document.querySelectorAll('.pm-card').length,inserts:document.querySelectorAll('.pm-insert').length,sub:document.querySelector('.pm-sub')?.textContent})));
await p.click('.pm-foot .btn-primary');
await p.waitForFunction(()=>document.querySelector('input[aria-label="页码"]')?.parentElement?.textContent?.includes('/ 11'),{timeout:30000});
await sleep(1200);
const input=await p.$('input[aria-label="页码"]'); await input.evaluate((el)=>el.select()); await input.type('7'); await p.keyboard.press('Enter'); await sleep(1200);
await p.screenshot({path:'review-m2/47-insert-applied-image.png'});
console.log('applied',await p.evaluate(()=>({page:document.querySelector('input[aria-label="页码"]')?.value,toast:document.querySelector('.toast')?.textContent,chip:document.querySelector('.save-chip')?.textContent})));
await b.disconnect();
