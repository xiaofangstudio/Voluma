import puppeteer from 'puppeteer-core';
import path from 'node:path';
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
const target=path.resolve('tmp-e2e/page5.pdf');
const b=await puppeteer.connect({browserURL:'http://127.0.0.1:9333',defaultViewport:null});
const p=(await b.pages()).find(x=>x.url().includes('tauri'));
const closeBtn=await p.$('button[aria-label="关闭文档"]');
if(closeBtn){ await closeBtn.click(); await sleep(700); }
await p.evaluate((pdfPath)=>{
  localStorage.setItem('voluma.recents.v1',JSON.stringify([{path:pdfPath,name:'page5',size:4684,pages:5,lastPage:1,zoom:100,updatedAt:Date.now()}]));
},target);
await p.reload({waitUntil:'networkidle2'});
await sleep(1200);
await p.waitForSelector('.recent-row',{timeout:10000});
await p.click('.recent-row');
await p.waitForFunction(()=>document.querySelectorAll('.page-wrap canvas').length>0,{timeout:20000});
await p.waitForFunction(()=>document.querySelector('.save-chip')?.textContent==='已保存',{timeout:10000});
await sleep(700);
const endPage=async()=>{
  await p.evaluate(()=>document.activeElement?.blur());
  await p.click('.page-wrap canvas');
  await p.keyboard.press('End');
  await p.waitForFunction(()=>document.querySelector('input[aria-label="页码"]')?.value==='5',{timeout:10000});
  await sleep(900);
};
await endPage();
const wrap=await p.evaluate(()=>{const r=document.querySelector('.page-wrap').getBoundingClientRect();return{x:r.x,y:r.y,w:r.width,h:r.height};});
console.log('wrap',wrap);
await p.click('button[aria-label="便签"]'); await sleep(250);
await p.mouse.click(wrap.x+70,wrap.y+200);
await p.waitForSelector('.note-composer textarea',{timeout:5000});
await p.type('.note-composer textarea','第五页的便签，验证多页注释写回。');
await p.click('.note-composer .btn-primary');
await p.waitForFunction(()=>document.querySelector('.save-chip')?.textContent==='已保存',{timeout:15000});
await sleep(600);
await p.screenshot({path:'review-m2/33-release-page5.png'});
await p.click('button[aria-label="注释列表"]'); await sleep(300);
const saved=await p.evaluate(()=>({chip:document.querySelector('.save-chip')?.textContent,annots:[...document.querySelectorAll('g.annot')].map(a=>a.getAttribute('class')),rows:[...document.querySelectorAll('.annot-row')].map(r=>r.textContent.trim()),page:document.querySelector('input[aria-label="页码"]')?.value}));
await p.screenshot({path:'review-m2/34-release-page5-list.png'});
console.log('saved',JSON.stringify(saved,null,2));
await p.click('button[aria-label="关闭文档"]'); await sleep(800);
await p.waitForSelector('.welcome',{timeout:10000});
const rows=await p.$$('.recent-row'); console.log('recent',rows.length); await rows[0].click();
await p.waitForFunction(()=>document.querySelectorAll('.page-wrap canvas').length>0,{timeout:20000});
await sleep(700); await endPage();
await p.waitForFunction(()=>document.querySelector('.save-chip')?.textContent==='已保存',{timeout:10000});
await sleep(500);
const back=await p.evaluate(()=>({chip:document.querySelector('.save-chip')?.textContent,annots:[...document.querySelectorAll('g.annot')].map(a=>a.getAttribute('class')),rows:[...document.querySelectorAll('.annot-row')].map(r=>r.textContent.trim()),page:document.querySelector('input[aria-label="页码"]')?.value}));
await p.screenshot({path:'review-m2/35-release-reopen.png'});
console.log('reopen',JSON.stringify(back,null,2));
await b.disconnect();
